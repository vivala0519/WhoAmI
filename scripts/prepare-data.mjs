const byId = (items, id) => items.find((x) => String(x.id) === String(id));
const players = raw.map((p) => {
  const assignment = p.clubAssignments.find((c) => c.type === 'current');
  const club = byId(entities.clubs, assignment?.clubId);
  const country = byId(
    entities.attributes.countries,
    p.nationalityDetails.nationalities.nationalityId,
  );
  const pos = byId(entities.attributes.positions, p.attributes.positionId);
  const league = club?.baseDetails.primaryCompetitionId;
  return {
    id: String(p.id),
    name:
      local.get(norm(p.name)) ??
      (/[가-힣]/.test(wiki[p.id] ?? '') ? wiki[p.id] : transliterations[p.id]) ??
      p.name,
    latin: p.name,
    country: countryNames[country.name] ?? country.name,
    countryId: String(country.id),
    countryCode: country.fifaCode,
    confederation: country.confederationId,
    club: clubNames[club.id] ?? club.name,
    clubId: String(club.id),
    clubCode:
      club.preferences.clubCode ||
      club.baseDetails.abbreviation ||
      club.name.slice(0, 3).toUpperCase(),
    league: leagues[league] ?? league,
    leagueId: league,
    position: positionNames[pos.id],
    positionCode: pos.shortName,
    positionId: pos.id,
    positionGroup: p.attributes.positionGroup,
    age: p.lifeDates.age,
    birthYear: Number(p.lifeDates.dateOfBirth.slice(0, 4)),
    number: assignment?.shirtNumber ?? null,
    value: p.marketValueDetails.current.value,
    color: club.baseDetails.superiorClub?.colors?.firstColor ?? '#4d657c',
  };
});
const world = pools.world.map(String);
const daily = players.filter((p) => p.leagueId === 'GB1' && p.value >= 3000000).map((p) => p.id);
await fs.writeFile(
  'src/players.json',
  JSON.stringify({ version: '2026-10-29', players, world, daily }),
);
